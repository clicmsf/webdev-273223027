import test from 'node:test';
import assert from 'node:assert/strict';
import { openDatabase, upsertDemoUser, hashPassword } from '../src/data/db.mjs';
import { createApp } from '../src/routes/http.mjs';

test('AC-1 AC-2 AC-3 AC-4 AC-12 AC-13 AC-14 real HTTP reservation lifecycle and refusals',async t=>{
 const db=openDatabase(':memory:'); upsertDemoUser(db,'test-only-password');
 db.prepare('INSERT INTO users(email,password_hash) VALUES (?,?)').run('second@example.test',hashPassword('test-only-password'));
 db.prepare('UPDATE events SET capacity=1 WHERE id=1').run();
 const server=createApp(db); await new Promise(r=>server.listen(0,'127.0.0.1',r));
 t.after(async()=>{await new Promise(r=>server.close(r));db.close();});
 const base=`http://127.0.0.1:${server.address().port}`;
 const req=(path,method='GET',cookie='',body)=>fetch(base+path,{method,headers:{Cookie:cookie,'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});
 const login=async email=>{const r=await req('/api/login','POST','',{email,password:'test-only-password'});assert.equal(r.status,200);return r.headers.get('set-cookie').split(';')[0];};
 const a=await login('student@example.test'),b=await login('second@example.test');
 assert.equal((await req('/api/registrations','POST','',{eventId:1})).status,401);
 const created=await req('/api/registrations','POST',a,{eventId:1});assert.equal(created.status,201);
 const registration=(await created.json()).registration;
 const full=await req('/api/registrations','POST',b,{eventId:1});assert.equal(full.status,409);assert.equal((await full.json()).error,'EventFull');
 const duplicate=await req('/api/registrations','POST',a,{eventId:1});assert.equal(duplicate.status,409);assert.equal((await duplicate.json()).error,'AlreadyRegistered');
 let events=(await (await req('/api/events','GET',a)).json()).events;
 assert.equal(events[0].free_places,0);assert.deepEqual(events.map(e=>e.id),[1,2,3]);
 assert.equal((await req(`/api/registrations/${registration.id}`,'DELETE',b)).status,403);
 assert.equal((await req(`/api/registrations/${registration.id}`,'DELETE')).status,401);
 assert.equal((await req('/api/registrations')).status,401);
 assert.equal((await (await req('/api/registrations','GET',b)).json()).registrations.length,0);
 assert.equal((await (await req('/api/registrations','GET',a)).json()).registrations.length,1);
 assert.equal((await req('/api/registrations','POST',a,{eventId:999})).status,404);
 assert.equal((await req('/api/registrations','POST',a,{eventId:'1'})).status,422);
 assert.equal((await req('/api/registrations','POST',a,null)).status,422);
 assert.equal((await req('/api/registrations/999','DELETE',a)).status,404);
 assert.equal((await req('/api/registrations/not-an-id','DELETE',a)).status,422);
 const bad=await fetch(base+'/api/registrations',{method:'POST',headers:{Cookie:a},body:'{'});assert.equal(bad.status,400);
 const simultaneous=await Promise.all([req('/api/registrations','POST',a,{eventId:2}),req('/api/registrations','POST',a,{eventId:2})]);
 assert.deepEqual(simultaneous.map(r=>r.status).sort(),[201,409]);
 assert.equal((await req(`/api/registrations/${registration.id}`,'DELETE',a)).status,204);
 events=(await (await req('/api/events','GET',a)).json()).events;assert.equal(events[0].free_places,1);
 assert.equal((await req('/api/registrations','POST',b,{eventId:1})).status,201);
});
